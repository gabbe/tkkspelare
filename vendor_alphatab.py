#!/usr/bin/env python3
"""Fetch alphaTab with its music font and soundfont into vendor/.

The deployed site has no runtime dependency on a CDN: the alphaTab build, the
Bravura font and the SONiVOX soundfont (sf3) are all served from vendor/, which
is git-ignored and fully regenerated by this script.

Usage:
    py vendor_alphatab.py [--version 1.9.0] [--out vendor/alphaTab.js]

Up to alphaTab 1.8.4 this script (then patch_alphatab.py) also patched the
playback order so that repeats finish before a D.C./D.S. on the same bar.
alphaTab 1.9.0 does that itself, so the build is now used unmodified.
"""
import argparse, pathlib, urllib.request

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--version', default='1.9.0')
    ap.add_argument('--out', default='vendor/alphaTab.js')
    a = ap.parse_args()
    base = f'https://cdn.jsdelivr.net/npm/@coderline/alphatab@{a.version}/dist/'
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    print('fetching', base + 'alphaTab.js')
    out.write_bytes(urllib.request.urlopen(base + 'alphaTab.js').read())
    print('wrote', out, f'({out.stat().st_size // 1024} kB)')
    assets = ['font/Bravura.woff2', 'font/Bravura.woff', 'font/Bravura.otf', 'font/Bravura.eot', 'font/Bravura.svg',
              'font/Bravura-OFL.txt', 'font/Bravura-FONTLOG.txt', 'soundfont/sonivox.sf3', 'soundfont/LICENSE', 'soundfont/README.md']
    for rel in assets:
        dst = out.parent / rel
        if dst.exists() and dst.stat().st_size > 0: continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(urllib.request.urlopen(base + rel).read())
        print('  fetched', rel, f'({dst.stat().st_size // 1024} kB)')

if __name__ == '__main__':
    main()
